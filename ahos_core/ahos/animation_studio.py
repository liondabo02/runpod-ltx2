    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(
            animation_studio_blueprint().to_dict(),
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    return destination