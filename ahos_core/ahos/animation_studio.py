def _worker(
    worker_id: str,
    name: str,
    role_name: str,
    team_id: str,
    reports_to: str | None,
    *capabilities: str,
) -> BusinessUnitWorker:
    return BusinessUnitWorker(
        worker_id=worker_id,
        name=name,
        role_name=role_name,
        team_id=team_id,
        reports_to=reports_to,
        capabilities=frozenset(capabilities),
        authority_level="B",
        paid_ai_enabled=False,
        external_actions_enabled=False,
    )


